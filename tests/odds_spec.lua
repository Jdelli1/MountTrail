-- Logic/Odds.lua: drop-chance arithmetic for the mount tooltip (pure).

describe("odds", function()
  local function load()
    return load_addon({ "Core/Locale.lua", "Logic/Odds.lua" }).Odds
  end

  describe("LuckyBy", function()
    it("is the attempt count by which half of all players have the mount", function()
      local O = load()
      eq(O.LuckyBy(100), 69, "ceil(ln 0.5 / ln 0.99) = ceil(68.97)")
      eq(O.LuckyBy(20), 14)
      eq(O.LuckyBy(10), 7)
      eq(O.LuckyBy(1000), 693)
      eq(O.LuckyBy(3), 2)
    end)

    it("does not round an exact integer up (1 in 2 -> 1)", function()
      eq(load().LuckyBy(2), 1)
    end)

    it("is 1 for a guaranteed drop and nil without a usable chance", function()
      local O = load()
      eq(O.LuckyBy(1), 1)
      eq(O.LuckyBy(0.5), 1, "better than certain counts as certain")
      eq(O.LuckyBy(0), nil)
      eq(O.LuckyBy(-5), nil)
      eq(O.LuckyBy(nil), nil)
      eq(O.LuckyBy("100"), nil)
    end)
  end)

  describe("ChanceSoFar", function()
    it("is 1 - (1 - 1/N)^A", function()
      local O = load()
      eq(string.format("%.4f", O.ChanceSoFar(100, 30)), "0.2603")
      eq(O.ChanceSoFar(100, 0), 0)
      eq(O.ChanceSoFar(2, 1), 0.5)
      eq(O.ChanceSoFar(1, 1), 1)
    end)

    it("is nil without a usable chance or attempt count", function()
      local O = load()
      eq(O.ChanceSoFar(0, 5), nil)
      eq(O.ChanceSoFar(nil, 5), nil)
      eq(O.ChanceSoFar(100, nil), nil)
      eq(O.ChanceSoFar(100, -1), nil)
    end)
  end)

  describe("Percent", function()
    it("formats a fraction with two decimals", function()
      local O = load()
      eq(O.Percent(O.ChanceSoFar(100, 30)), "26.03%")
      eq(O.Percent(0), "0.00%")
      eq(O.Percent(1), "100.00%")
      eq(O.Percent(nil), nil)
    end)
  end)
end)
