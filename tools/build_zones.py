#!/usr/bin/env python3
"""Writes Data/Zones.lua: zone maps that share their name with another zone map.

Several zones exist in more than one version, each its own UI map with the same
name: The Burning Crusade's and Warlords of Draenor's Nagrand and Shadowmoon
Valley, Cataclysm's Uldum and its 8.3 assault version, the Midnight Eversong
Woods, Isle of Quel'Danas and Silvermoon City next to the originals, and more.
A mount whose only location is the source text's "Zone: <name>" line must be
listed in one version, not every map of that name (Logic/Zone.lua).

For every zone-type UI map in the world map's tree (UiMap.db2, Type 3, parents
up to Cosmic 946) whose name another such map has, the file gives its name
group and its expansion: the map's own ContentTuning ExpansionID, else that of
the nearest zone-type map above it (a sub-zone of the Midnight Eversong Woods
is Midnight), else none (continents are not used: Eastern Kingdoms itself is
tuned for the newest expansion).

Source of truth: Blizzard's UiMap and ContentTuning tables as CSV from
wago.tools (tools/verify_data.py downloads and caches them), at the build
pinned in tools/sources.json ("db2build").

    python tools/build_zones.py              # pinned build, cached tables
    python tools/build_zones.py --offline    # cache only
"""

import argparse
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import verify_data  # noqa: E402  (fetch_tables, read_csv)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Data", "Zones.lua")
SOURCES = os.path.join(ROOT, "tools", "sources.json")

COSMIC = 946
ZONE = 3
CONTINENT = 2
MAX_STEPS = 20
EXPANSIONS = ("Classic", "The Burning Crusade", "Wrath of the Lich King", "Cataclysm",
              "Mists of Pandaria", "Warlords of Draenor", "Legion", "Battle for Azeroth",
              "Shadowlands", "Dragonflight", "The War Within", "Midnight")


def _int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def name_key(name):
    """Comparable zone name: lower case, trimmed, single spaces, a leading "the " dropped."""
    name = " ".join((name or "").split()).lower()
    if name.startswith("the "):
        name = name[4:]
    return name


def zone_versions(uimap_rows, tuning_rows):
    """-> {uiMapID: (group, expansion index or None)} for zone maps in the world map's
    tree that share their name with another one; groups are numbered from 1 in order of
    their lowest map ID."""
    maps = {_int(r["ID"]): r for r in uimap_rows}
    tuning = {_int(r["ID"]): _int(r["ExpansionID"]) for r in tuning_rows}

    def parent(i):
        return _int(maps[i]["ParentUiMapID"]) if i in maps else 0

    def kind(i):
        return _int(maps[i]["Type"]) if i in maps else None

    def in_tree(i):
        for _ in range(MAX_STEPS):
            if i == COSMIC:
                return True
            i = parent(i)
            if not i:
                return False
        return False

    def own_expansion(i):
        e = tuning.get(_int(maps[i]["ContentTuningID"]), -1)
        return e if 0 <= e < len(EXPANSIONS) else None

    def expansion(i):
        current = i
        for _ in range(MAX_STEPS):
            if current not in maps or kind(current) is None or kind(current) <= CONTINENT:
                return None
            if kind(current) == ZONE:
                e = own_expansion(current)
                if e is not None:
                    return e
            current = parent(current)
            if not current:
                return None
        return None

    by_name = collections.defaultdict(list)
    for i, r in maps.items():
        if kind(i) == ZONE and name_key(r["Name_lang"]) and in_tree(i):
            by_name[name_key(r["Name_lang"])].append(i)
    groups = sorted((sorted(ids) for ids in by_name.values() if len(ids) > 1), key=lambda ids: ids[0])
    out = {}
    for g, ids in enumerate(groups, 1):
        for i in ids:
            out[i] = (g, expansion(i))
    return out, {i: maps[i]["Name_lang"] for i in out}


def emit_lua(versions, names, build):
    lines = [
        "-- GENERATED by tools/build_zones.py from Blizzard's UiMap and ContentTuning tables",
        "-- (Retail build %s, wago.tools) -- do not edit." % build,
        "-- Zone maps that share their name with another zone map: uiMapID -> { g = name",
        "-- group, e = expansion (0 Classic ... 11 Midnight; absent: none) }. Logic/Zone.lua lists",
        "-- a mount known only by its source text's zone name in the version of its expansion.",
        "",
        "local ADDON, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.ZoneVersions = {",
    ]
    for i in sorted(versions, key=lambda k: (versions[k][0], k)):
        g, e = versions[i]
        body = "g = %d" % g if e is None else "g = %d, e = %d" % (g, e)
        lines.append("  [%d] = { %s }, -- %s%s" % (i, body, names[i], "" if e is None else " (%s)" % EXPANSIONS[e]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def pinned_build():
    with open(SOURCES, encoding="utf-8") as fh:
        build = json.load(fh).get("db2build")
    if not build:
        sys.exit("no db2build pinned in tools/sources.json")
    return build


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", help="DB2 build (default: db2build in tools/sources.json)")
    ap.add_argument("--offline", action="store_true", help="use the cached tables only")
    args = ap.parse_args(argv)
    build = args.build or pinned_build()
    folder = verify_data.fetch_tables(build, offline=args.offline, tables=("UiMap", "ContentTuning"))
    versions, names = zone_versions(verify_data.read_csv(os.path.join(folder, "UiMap.csv")),
                                    verify_data.read_csv(os.path.join(folder, "ContentTuning.csv")))
    text = emit_lua(versions, names, build)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("zone versions: %d maps in %d name groups -> %s" % (
        len(versions), len({g for g, _ in versions.values()}), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
