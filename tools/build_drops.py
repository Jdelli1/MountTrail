#!/usr/bin/env python3
"""Writes Data/JournalDrops.lua: which difficulties each boss-drop mount drops on.

The Encounter Journal (the Adventure Guide) knows each boss's loot per
difficulty. For every mount in Data/Mounts.lua whose item is a boss's loot
(JournalEncounterItem.ItemID), this records the instance (JournalInstance.MapID:
the instance ID GetInstanceInfo returns in game) and the difficulty IDs it
drops on (JournalItemXDifficulty rows for that loot entry). A loot entry with
no rows drops on every difficulty, and gets no list. The wrong-difficulty
warning (UI/DifficultyCheck.lua, Lockouts.WrongDifficulty) trusts this over the
hand-written lockout specs.

Source of truth: Blizzard's JournalEncounterItem, JournalEncounter,
JournalInstance and JournalItemXDifficulty tables as CSV from wago.tools
(tools/verify_data.py downloads and caches them), at the build pinned in
tools/sources.json ("db2build").

    python tools/build_drops.py              # pinned build, cached tables
    python tools/build_drops.py --offline    # cache only
"""

import argparse
import collections
import json
import os
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)
import verify_data  # noqa: E402  (fetch_tables, read_csv, load_our_data)

SOURCES = os.path.join(ROOT, "tools", "sources.json")
OUT = os.path.join(ROOT, "Data", "JournalDrops.lua")
TABLES = ("JournalEncounterItem", "JournalEncounter", "JournalInstance", "JournalItemXDifficulty")


def _int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def journal_drops(mounts, encounter_items, encounters, instances, item_difficulties):
    """mounts: { mountID: { item = } } -> { mountID: { "map": id, "d": [ids] or None } }.

    A mount that drops from bosses of more than one instance keeps the
    instance with the lowest map ID (stable); its difficulties are the union
    over that instance's loot entries, None as soon as one has no list."""
    by_item = collections.defaultdict(list)
    for r in encounter_items:
        by_item[_int(r["ItemID"])].append(r)
    enc = {_int(r["ID"]): r for r in encounters}
    inst = {_int(r["ID"]): r for r in instances}
    diffs = collections.defaultdict(set)
    for r in item_difficulties:
        diffs[_int(r["JournalEncounterItemID"])].add(_int(r["DifficultyID"]))
    out = {}
    for mid in sorted(mounts):
        item = _int(mounts[mid].get("item"))
        if not item or item not in by_item:
            continue
        per_map = {}
        for row in by_item[item]:
            e = enc.get(_int(row["JournalEncounterID"]))
            i = e and inst.get(_int(e["JournalInstanceID"]))
            m = i and _int(i["MapID"])
            if not m:
                continue
            ds = diffs.get(_int(row["ID"]))
            if m not in per_map:
                per_map[m] = set(ds) if ds else None
            elif per_map[m] is not None:
                if ds:
                    per_map[m] |= ds
                else:
                    per_map[m] = None
        if per_map:
            m = min(per_map)
            out[mid] = {"map": m, "d": sorted(per_map[m]) if per_map[m] else None}
    return out


def emit_lua(drops, mounts, build):
    lines = [
        "-- GENERATED by tools/build_drops.py from Blizzard's Encounter Journal tables",
        "-- (Retail build %s, wago.tools) -- do not edit." % build,
        "-- mountID -> { map = the instance's ID (GetInstanceInfo's 8th return), d = the",
        "-- difficulty IDs it drops on (absent: every difficulty) }. Read by the",
        "-- wrong-difficulty warning (Lockouts.WrongDifficulty).",
        "",
        "local ADDON, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.JournalDrops = {",
    ]
    for mid in sorted(drops):
        d = drops[mid]
        body = "map = %d" % d["map"]
        if d["d"]:
            body += ", d = { %s }" % ", ".join(str(x) for x in d["d"])
        lines.append("  [%d] = { %s }, -- %s" % (mid, body, mounts[mid].get("name", "")))
    lines.append("}")
    return "\n".join(lines) + "\n"


def pinned_build():
    with open(SOURCES, encoding="utf-8") as fh:
        build = json.load(fh).get("db2build")
    if not build:
        sys.exit("no db2build pinned in tools/sources.json")
    return build


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--build", help="DB2 build (default: db2build in tools/sources.json)")
    ap.add_argument("--offline", action="store_true", help="use the cached tables only")
    args = ap.parse_args(argv)
    build = args.build or pinned_build()
    folder = verify_data.fetch_tables(build, offline=args.offline, tables=TABLES)
    read = lambda t: verify_data.read_csv(os.path.join(folder, t + ".csv"))  # noqa: E731
    mounts = verify_data.load_our_data()["mounts"]
    drops = journal_drops(mounts, read("JournalEncounterItem"), read("JournalEncounter"),
                          read("JournalInstance"), read("JournalItemXDifficulty"))
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(emit_lua(drops, mounts, build))
    print("journal drops: %d mounts (%d on chosen difficulties) -> %s" % (
        len(drops), sum(1 for d in drops.values() if d["d"]), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
